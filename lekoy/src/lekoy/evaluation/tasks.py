"""Evaluation suites: what is asked, and how the answer is scored.

Each suite is a list of items in a common shape, so `runner.py` does not need
to know which benchmark it is running:

    {"id", "prompt", "scorer", plus whatever that scorer needs}

Three sources feed the suites. Hand-written items (the Hebrew benchmark, the
translation, hallucination, identity and instruction-following suites) live in
Python. Downloaded benchmarks (Belebele, Global-MMLU, GSM8K) are read from
data/raw/ and reshaped here. Nothing is generated by a model, and nothing is
scored by one.
"""
from __future__ import annotations

import json
from pathlib import Path

from ..identity import FAMILY, FULL_NAME, IDENTITY_QA, MODEL
from ..paths import EVAL, RAW
from . import hebrew_benchmark


def _read(path: Path, limit: int | None = None) -> list[dict]:
    if not path.exists():
        return []
    out = []
    with path.open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                out.append(json.loads(line))
                if limit and len(out) >= limit:
                    break
    return out


def _materialised(suite: str, limit: int | None = None) -> list[dict]:
    """Read a suite from the copy under `eval/`, if one has been written.

    The downloaded benchmarks are reshaped from `data/raw/`, which is not in
    version control — it is gigabytes of corpus. That made a fresh clone unable
    to load Belebele, Global-MMLU or GSM8K at all, and the suite-integrity test
    failed on it: the benchmarks were reproducible only on the machine that had
    already downloaded them, which is not reproducible.

    `scripts/build_eval.py` writes every suite to `eval/` as JSONL and those
    files *are* committed, so this reads them when the raw data is absent. The
    result is that the benchmarks travel with the repository.
    """
    for path in EVAL.rglob(f"{suite}.jsonl"):
        items = _read(path, limit)
        if items:
            return items
    return []


