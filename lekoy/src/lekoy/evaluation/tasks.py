def belebele(language: str, limit: int | None = 120) -> list[dict]:
    """Parallel reading comprehension, 4-way multiple choice."""
    folder = {"hebrew": "hebrew", "english": "english", "spanish": "spanish"}[language]
    rows = _read(RAW / folder / f"belebele_{language}.jsonl", limit)
    if not rows:
        return _materialised(f"belebele_{language}", limit)
    instruction = {
        "hebrew": "קרא את הקטע וענה על השאלה. ענה באות בלבד (A, B, C או D).",
        "english": "Read the passage and answer the question. "
                   "Answer with the letter only (A, B, C or D).",
        "spanish": "Lee el pasaje y responde la pregunta. "
                   "Responde solo con la letra (A, B, C o D).",
    }[language]
    items = []
    for i, row in enumerate(rows):
        answers = [row.get(f"mc_answer{n}") for n in (1, 2, 3, 4)]
        correct = row.get("correct_answer_num")
        if not all(answers) or correct not in ("1", "2", "3", "4", 1, 2, 3, 4):
            continue
        options = "\n".join(f"{letter}. {answer}"
                            for letter, answer in zip("ABCD", answers))
        items.append({
            "id": f"belebele_{language}_{i:03d}",
            "suite": f"belebele_{language}", "scorer": "choice", "num_options": 4,
            "correct": "ABCD"[int(correct) - 1],
            "prompt": f"{instruction}\n\n{row.get('text', '')}\n\n"
                      f"{row.get('question', '')}\n{options}",
        })
    return items


def global_mmlu(language: str, limit: int | None = 150) -> list[dict]:
    code = {"hebrew": "hebrew", "english": "english", "spanish": "spanish"}[language]
    rows = _read(RAW / code / f"global_mmlu_{language}.jsonl", limit)
    if not rows:
        return _materialised(f"global_mmlu_{language}", limit)
    instruction = {
        "hebrew": "ענה על שאלת הידע הבאה. ענה באות בלבד (A, B, C או D).",
        "english": "Answer the following knowledge question. "
                   "Answer with the letter only (A, B, C or D).",
        "spanish": "Responde la siguiente pregunta. "
                   "Responde solo con la letra (A, B, C o D).",
    }[language]
    items = []
    for i, row in enumerate(rows):
        options = [row.get(f"option_{k}") for k in "abcd"]
        answer = (row.get("answer") or "").strip().upper()
        if not all(options) or answer not in "ABCD":
            continue
        rendered = "\n".join(f"{letter}. {option}"
                             for letter, option in zip("ABCD", options))
        items.append({
            "id": f"gmmlu_{language}_{i:03d}",
            "suite": f"global_mmlu_{language}", "scorer": "choice",
            "num_options": 4, "correct": answer,
            "subject": row.get("subject"),
            "prompt": f"{instruction}\n\n{row.get('text', '')}\n{rendered}",
        })
    return items


def gsm8k(limit: int | None = 60) -> list[dict]:
    rows = _read(RAW / "english" / "gsm8k_test.jsonl", limit)
    if not rows:
        return _materialised("gsm8k", limit)
    items = []
    for i, row in enumerate(rows):
        messages = row.get("messages") or []
        if len(messages) < 2:
            continue
        question = messages[0]["content"]
        answer = messages[-1]["content"]
        items.append({
            "id": f"gsm8k_{i:03d}", "suite": "gsm8k", "scorer": "numeric",
            "answer": answer,
            "prompt": f"{question}\n\nSolve it and give the final numeric answer.",
        })
    return items


