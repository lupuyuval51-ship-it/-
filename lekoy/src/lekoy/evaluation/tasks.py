# Suites that must run with no system prompt.
#
# The identity suite is the reason this exists, and the reason is worth
# recording. The LEKOY system prompt opens with "You are LEKOY RV5" — so with
# it in context an *untrained* Qwen base answers "אני LEKOY RV5" and scores a
# perfect 1.000, purely by reading its own name out of the prompt it was just
# given. Without the prompt the same checkpoint says "Qwen" and scores 0.000.
# Identity training is meant to put the name in the weights; measuring it with
# the answer in the context measures nothing at all.
NO_SYSTEM_PROMPT_SUITES = frozenset({"identity"})


# Suites the LEKOY SCORE needs, in the order a report should present them.
DEFAULT_SUITES = [
    "hebrew", "english", "spanish", "reasoning", "math", "coding",
    "translation", "instruction_following", "hallucination", "identity",
    "belebele_hebrew", "belebele_english", "belebele_spanish",
    "global_mmlu_hebrew", "global_mmlu_english", "global_mmlu_spanish", "gsm8k",
]


def load(names: list[str] | None = None, limit: int | None = None) -> dict[str, list[dict]]:
    names = names or DEFAULT_SUITES
    unknown = set(names) - set(SUITES)
    if unknown:
        raise KeyError(f"unknown suite(s): {sorted(unknown)}; "
                       f"available: {sorted(SUITES)}")
    out = {}
    for name in names:
        items = SUITES[name]()
        if limit:
            items = items[:limit]
        if items:
            out[name] = items
    return out
