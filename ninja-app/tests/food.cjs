const P = require('./paths.cjs');
const { chromium } = require('playwright');
const out = process.argv[2] || require('path').join(require('os').tmpdir(), 'ninja-shots'); require('fs').mkdirSync(out, { recursive: true });
const URL = P.APP;
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const page = await ctx.newPage();
  const errs = [];
  page.on('pageerror', e => errs.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error') errs.push('console: ' + m.text()); });
  const shot = async n => { await page.waitForTimeout(250); await page.screenshot({ path: `${out}/${n}.png` }); };
  const ovf = async n => { const o = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth); if (o > 0) errs.push(`overflow ${o}px on ${n}`); };
  const click = async (sel, opts = {}) => { await page.$eval(sel, e => e.scrollIntoView({ block: 'center' })); await page.click(sel, { force: true, ...opts }); await page.waitForTimeout(120); };
  await page.goto(URL); await page.waitForTimeout(1200); await page.evaluate(() => { const b = document.querySelector('[data-act="lang"][data-v="he"]'); b && b.click(); }); await page.waitForTimeout(250);
  await shot('01-welcome'); await ovf('welcome');
  await require('./onb.cjs')(page, click, { name: 'יובל' });
  await click('[data-act="ob-finish"]'); await page.waitForTimeout(400);
  await page.waitForTimeout(400);
  const ok = (n, v) => console.log((v ? 'PASS ' : 'FAIL ') + n);
  await click('[data-act="tab"][data-v="food"]'); await page.waitForTimeout(900);
  await shot('40-food'); await ovf('food');
  ok('300 dishes counted, first 36 shown', (await page.$$('.fcard')).length === 36 && /300/.test(await page.$eval('.food-count', e => e.textContent)));
  await page.screenshot({ path: out + '/40b-food-full.png', fullPage: false });
  await page.fill('[data-bind="food-q"]', 'שקשוקה'); await page.waitForTimeout(300);
  const n1 = (await page.$$('.fcard')).length; ok('search filters (' + n1 + ')', n1 >= 3 && n1 < 10);
  ok('search keeps focus', await page.evaluate(() => document.activeElement && document.activeElement.dataset.bind === 'food-q'));
  await page.fill('[data-bind="food-q"]', ''); await page.waitForTimeout(200);
  await click('[data-act="food-cat"][data-v="post"]'); await page.waitForTimeout(300);
  ok('category filter', (await page.$$('.fcard')).length === 26);
  await click('[data-act="food-tag"][data-v="vg"]'); await page.waitForTimeout(300);
  const n2 = (await page.$$('.fcard')).length; ok('tag filter (' + n2 + ')', n2 > 0 && n2 < 26);
  await click('.fcard'); await page.waitForTimeout(600); await shot('41-dish'); await ovf('dish');
  ok('dish sheet open', !!(await page.$('.sheet .macro')));
  await click('[data-act="dish-fav"]'); await page.waitForTimeout(300);
  ok('favorite saved', await page.evaluate(() => (JSON.parse(localStorage.getItem('ninja-circuit-v1')).prefs.favFood || []).length === 1));
  await page.keyboard.press('Escape'); await page.waitForTimeout(300);
  await click('[data-act="food-cat"][data-v="fav"]'); await page.waitForTimeout(300);
  ok('favorites tab shows it', (await page.$$('.fcard')).length === 1);
  await click('[data-act="food-cat"][data-v="all"]'); await click('[data-act="food-tag"][data-v="vg"]'); await page.waitForTimeout(300);
  await page.evaluate(() => window.scrollTo(0, 0)); await shot('42-food-top');
  await click('[data-act="lang"][data-v="en"]').catch(() => {});
  console.log('errors:', JSON.stringify(errs));
  await browser.close();
})();
