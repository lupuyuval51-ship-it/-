// Bundles the LEVEL UP AI Edge Function (src/server/ai/edge) into one self-contained ES module for Supabase's Deno runtime:
//   node scripts/build-ai-function.mjs   →   supabase/functions/generate-game/game.js
// The deployed `index.ts` imports that file from GitHub at a pinned commit (see supabase/functions/generate-game/README.md).
// Everything is bundled (zod, the Anthropic SDK); nothing in it is a secret: keys are read from the function's secrets at runtime.
import { build } from "esbuild";
import { statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const stub = (name) => path.join(root, "src/server/ai/edge/stubs", name);
const outfile = path.join(root, "supabase/functions/generate-game/game.js");

await build({
  entryPoints: [path.join(root, "src/server/ai/edge/deno-entry.ts")],
  outfile,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  legalComments: "eof",
  tsconfig: path.join(root, "tsconfig.json"),
  alias: {
    "server-only": stub("server-only.ts"),
    "@/lib/game/topics/loaders": stub("topic-loaders.ts"),
  },
  banner: { js: "// LEVEL UP AI — generate-game Edge Function. Generated by scripts/build-ai-function.mjs; do not edit." },
  logLevel: "warning",
});
console.log(`${path.relative(root, outfile)}: ${(statSync(outfile).size / 1024).toFixed(0)} kB`);
