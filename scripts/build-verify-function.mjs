// Bundles the purchase-verification Edge Function (src/server/play) into one self-contained module for Supabase's Deno runtime:
//   node scripts/build-verify-function.mjs   →   supabase/functions/verify-purchase/index.ts
// Readable on purpose (not minified): it is the code that decides who gets a paid plan. Nothing in it is a secret: the Google
// service account key is read from the function's secrets (PLAY_SERVICE_ACCOUNT_JSON) at runtime.
import { build } from "esbuild";
import { statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outfile = path.join(root, "supabase/functions/verify-purchase/index.ts");

await build({
  entryPoints: [path.join(root, "src/server/play/edge-entry.ts")],
  outfile,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: false,
  legalComments: "none",
  tsconfig: path.join(root, "tsconfig.json"),
  banner: { js: "// @ts-nocheck\n// LEVEL UP — verify-purchase Edge Function. Generated by scripts/build-verify-function.mjs; do not edit." },
  logLevel: "warning",
});
console.log(`${path.relative(root, outfile)}: ${(statSync(outfile).size / 1024).toFixed(0)} kB`);
