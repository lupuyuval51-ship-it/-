#!/usr/bin/env tsx
/**
 * Bundles server/migrations/*.sql into server/src/db/migrationsBundle.ts (so the same migrations run in Node and in
 * the browser Device Mode worker) and enforces pinned checksums. CRLF is normalised to LF BEFORE hashing, so a Windows
 * checkout can never cause schema drift. A changed, already-pinned migration fails; only NEW migrations are added.
 */
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const dir = join(root, 'server/migrations');
const pinFile = join(dir, 'checksums.json');
const pinned: Record<string, string> = existsSync(pinFile) ? (JSON.parse(readFileSync(pinFile, 'utf8')) as Record<string, string>) : {};
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const items: { name: string; sql: string; sha256: string }[] = [];
let failed = false;
for (const f of files) {
  const sql = readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n');
  const sha256 = createHash('sha256').update(sql).digest('hex');
  const pin = pinned[f];
  if (pin && pin !== sha256) { console.error(`DRIFT: ${f} changed after being pinned (${pin} -> ${sha256}). Migrations are forward-only: add a new migration instead.`); failed = true; }
  if (!pin) pinned[f] = sha256;
  items.push({ name: f, sql, sha256 });
}
if (failed) process.exit(1);
writeFileSync(pinFile, `${JSON.stringify(pinned, null, 2)}\n`);
writeFileSync(join(root, 'server/src/db/migrationsBundle.ts'), `// GENERATED by scripts/gen-migrations.ts. Do not edit.\nexport const MIGRATIONS: { name: string; sql: string; sha256: string }[] = ${JSON.stringify(items, null, 2)};\nexport const PINNED_CHECKSUMS: Record<string, string> = ${JSON.stringify(pinned, null, 2)};\n`);
console.log(`bundled ${items.length} migrations`);
