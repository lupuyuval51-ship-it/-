#!/usr/bin/env tsx
/** Regenerates shared/src/content/data/readyWorkouts.generated.ts deterministically from the exercise library. */
import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { EXERCISES_ALL } from '../shared/src/content/sources.ts';
import { generateReadyWorkouts } from '../shared/src/content/workoutGenerator.ts';

const { workouts, skipped } = generateReadyWorkouts(EXERCISES_ALL);
const body = JSON.stringify(workouts, null, 2).replace(/"([a-zA-Z]+)":/g, '$1:').replace(/"/g, "'");
const file = join(resolve(import.meta.dirname, '..'), 'shared/src/content/data/readyWorkouts.generated.ts');
writeFileSync(file, `// GENERATED by scripts/gen-ready-workouts.ts. Do not edit by hand. Run: npm run gen:workouts\nimport type { ReadyWorkoutContent } from '../types.js';\n\nexport const READY_WORKOUTS_GENERATED: ReadyWorkoutContent[] = ${body};\n`);
console.log(`generated ${workouts.length} ready workouts (${skipped.length} specs skipped)`);
if (skipped.length) console.log('skipped:', skipped.join(', '));
