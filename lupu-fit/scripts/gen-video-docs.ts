#!/usr/bin/env tsx
/** Generates docs/exercise-video-list.md and docs/exercise-video-prompts.csv from the exercise library. */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { EXERCISES_ALL } from '../shared/src/content/sources.ts';
import { isHighImpact } from '../shared/src/age.ts';

const root = resolve(import.meta.dirname, '..');
mkdirSync(join(root, 'docs'), { recursive: true });
const check = (e: (typeof EXERCISES_ALL)[number]) => e.difficulty === 'advanced' || isHighImpact(e);
const order = ['A', 'B', 'C', 'D'] as const;
const sorted = [...EXERCISES_ALL].sort((a, b) => order.indexOf(a.videoPriority) - order.indexOf(b.videoPriority) || a.id.localeCompare(b.id));

let md = `# Exercise video list\n\nGenerated by \`npm run gen:docs\`. ${EXERCISES_ALL.length} exercises. Priority A clips are bundled offline.\n\nSpec per clip: MP4, H.264, +faststart, silent, 6-10 s seamless loop, 720x720 (or 720x1280), <= 4 MB, poster JPG <= 60 KB.\nPath: \`/media/exercises/<id>.mp4\`, \`/media/exercises/<id>.jpg\`.\n\n`;
for (const p of order) {
  const rows = sorted.filter((e) => e.videoPriority === p);
  md += `## Priority ${p} (${rows.length})\n\n| id | Hebrew | English | equipment | check twice |\n|---|---|---|---|---|\n`;
  for (const e of rows) md += `| \`${e.id}\` | ${e.nameHe} | ${e.nameEn} | ${e.equipment.join(', ')} | ${check(e) ? 'yes' : ''} |\n`;
  md += '\n';
}
writeFileSync(join(root, 'docs/exercise-video-list.md'), md);

const q = (s: string) => `"${s.replace(/"/g, '""')}"`;
let csv = 'id,priority,check_twice,prompt\n';
for (const e of sorted) {
  const prompt = `Silent seamless 8-second loop, fixed camera, plain studio background, athlete performing ${e.nameEn} with correct form. Key points: ${e.stepsEn.join('; ')}. Avoid: ${e.mistakesEn.join('; ')}.`;
  csv += `${e.id},${e.videoPriority},${check(e) ? 'yes' : 'no'},${q(prompt)}\n`;
}
writeFileSync(join(root, 'docs/exercise-video-prompts.csv'), csv);
console.log(`wrote video docs for ${EXERCISES_ALL.length} exercises`);
